def replace_lists(src: Path, out: Path) -> None:
    doc = Document(src)
    paragraphs = list(doc.paragraphs)

    for idx, count, text in OPS:
        paragraphs[idx - 1].text = text
        for remove_idx in range(idx + count, idx, -1):
            element = paragraphs[remove_idx - 1]._element
            parent = element.getparent()
            if parent is not None:
                parent.remove(element)

    doc.save(out)


